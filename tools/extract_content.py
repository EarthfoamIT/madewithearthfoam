#!/usr/bin/env python3
"""Extract readable page content from the mirrored HTML into Markdown.

Usage: python3 -I tools/extract_content.py site > CONTENT.md
"""
import os, re, sys
from html.parser import HTMLParser

PAGES = ["index.html", "increasing-access-to-healthcare/index.html",
         "improving-productivity-and-working-conditions/index.html",
         "strengthening-the-community/index.html", "half-height-pillow/index.html", "404.html"]
BLOCK = {"h1", "h2", "h3", "h4", "p", "figcaption", "li", "button", "span", "a", "div", "label"}


class Extract(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out, self.buf, self.skip, self.stack = [], [], 0, []
        self.meta, self.title, self.in_title = {}, "", False

    def flush(self):
        t = re.sub(r"\s+", " ", "".join(self.buf)).strip()
        if t and self.stack:
            tag = self.stack[-1]
            prefix = {"h1": "# ", "h2": "## ", "h3": "### ", "h4": "#### ", "li": "- "}.get(tag, "")
            if tag == "figcaption":
                prefix = "_Caption:_ "
            elif tag == "button":
                prefix = "_[Button]_ "
            if not self.out or self.out[-1] != prefix + t:
                self.out.append(prefix + t)
        self.buf = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "noscript"):
            self.skip += 1
            return
        if tag == "title":
            self.in_title = True
        if tag == "meta" and (a.get("name") or a.get("property")):
            self.meta[a.get("name") or a.get("property")] = a.get("content", "")
        if self.skip:
            return
        if tag in BLOCK:
            self.flush()
            self.stack.append(tag)
        if tag == "img":
            self.flush()
            self.out.append(f"![{a.get('alt', '')}]({a.get('src', '')})")
        if tag == "source" and a.get("src"):
            self.out.append(f"[video source: {a['src']}{' media=' + a['media'] if a.get('media') else ''}]")
        if tag == "track":
            self.out.append(f"[captions: {a.get('src')} ({a.get('srclang')})]")
        if tag == "a" and a.get("href"):
            self.stack[-1] = ("a", a["href"])
        if tag == "form":
            self.out.append(f"[form → {a.get('method', 'get').upper()} {a.get('action')}]")
        if tag == "input":
            self.out.append(f"[input type={a.get('type')} name={a.get('name')}"
                            f"{' placeholder=' + repr(a['placeholder']) if a.get('placeholder') else ''}"
                            f"{' value=' + a['value'] if a.get('value') else ''}]")

    def handle_endtag(self, tag):
        if tag in ("script", "style", "noscript"):
            self.skip -= 1
            return
        if tag == "title":
            self.in_title = False
        if self.skip:
            return
        if tag in BLOCK and self.stack:
            top = self.stack[-1]
            if isinstance(top, tuple):
                t = re.sub(r"\s+", " ", "".join(self.buf)).strip()
                if t:
                    self.out.append(f"[{t}]({top[1]})")
                self.buf = []
            else:
                self.flush()
            self.stack.pop()

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        elif not self.skip:
            self.buf.append(data)


root = sys.argv[1]
print("# Site Content (extracted from mirror)\n")
print("Generated by `tools/extract_content.py` from the HTML in `site/`. "
      "Order follows the DOM. Images are shown as `![alt](src)`. The header, "
      "footer, image carousel and newsletter block repeat on every page and are "
      "only listed in full for the home page.\n")
for page in PAGES:
    html = open(os.path.join(root, page), encoding="utf-8").read()
    p = Extract()
    p.feed(html)
    url = "/" + page.replace("index.html", "").rstrip("/")
    print(f"\n---\n\n## Page: `{url or '/'}`\n")
    print(f"- **Title:** {p.title.strip()}")
    for k in ("description", "og:url", "og:image", "og:image:alt"):
        if k in p.meta:
            print(f"- **{k}:** {p.meta[k]}")
    print()
    lines = p.out
    if page != "index.html":
        # keep only <main> content for subpages
        m = re.search(r"<main>(.*?)</main>", html, re.S)
        sub = Extract()
        sub.feed(m.group(1))
        lines = sub.out
    for line in lines:
        # demote headings so they nest under the page heading
        if line.startswith("#"):
            line = "##" + line
        print(line + "\n")
